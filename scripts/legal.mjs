// The Privacy and terms page (#terms) has ONE source: legal/terms.md (A709 M2, founder 2026-11-25: "Can we move the rest of the
// services' terms now?"). legal.333.eco publishes every version of that file; this page renders it through
// src/ui/legal-terms.ts, which scripts/gen-legal.mjs generates from it. Pure functions here, so the tests can break each one.
import { createHash } from "node:crypto";

// The shape legal.333.eco's release accepts: "# Title", a blank line, then the date line.
export const DATE_LINE = /^(Draft|Version) of (\d{1,2}) ([A-Za-z]+) (\d{4})\.$/;

/** legal/terms.md → what src/ui/terms.ts renders: the title, the date line, the sections (a heading and its paragraphs, each
 *  drawn as a card) and the closing contact line. ⛔ Anything this page cannot draw faithfully is REFUSED, never dropped: a
 *  list, a table, emphasis, code, a link, raw HTML, a third-level heading, text before the first heading. Teach the
 *  renderer (and its test) first if the document ever needs one. */
export function parseTerms(md) {
    if (md.includes("\r")) throw new Error("legal/terms.md: CR line endings; use LF only");
    const lines = md.split("\n");
    const title = /^# (.+)$/.exec(lines[0] ?? "")?.[1];
    if (!title) throw new Error("legal/terms.md: the first line must be '# <Title>'");
    if (lines[1] !== "") throw new Error("legal/terms.md: the second line must be blank");
    if (!DATE_LINE.test(lines[2] ?? "")) throw new Error(`legal/terms.md: the third line must read "Draft of D Month YYYY." or "Version of D Month YYYY.", not ${JSON.stringify(lines[2] ?? "")}`);
    const dateLine = lines[2];
    const blocks = lines.slice(3).join("\n").split(/\n\s*\n/).map((b) => b.trim()).filter(Boolean);
    const last = blocks.pop() ?? "";
    if (!/^Contact: \S+$/.test(last)) throw new Error("legal/terms.md: the last paragraph must be the contact line ('Contact: <address>')");
    const sections = [];
    for (const b of blocks) {
        const bad = /^(#(?!# )|###|[-*+] |\d+\. |\||>|```)|[*_`<\\]|\[.*\]\(/m.exec(b);
        if (bad) throw new Error(`legal/terms.md: this page cannot render ${JSON.stringify(bad[0])} in: ${b.slice(0, 80)}`);
        if (b.startsWith("## ")) {
            if (b.includes("\n")) throw new Error(`legal/terms.md: a heading is one line, followed by a blank line: ${b.slice(0, 80)}`);
            sections.push([b.slice(3), []]);
            continue;
        }
        if (!sections.length) throw new Error("legal/terms.md: text before the first '## ' heading has no place on this page");
        sections.at(-1)[1].push(b.replace(/\s*\n\s*/g, " "));
    }
    const empty = sections.find(([, ps]) => !ps.length);
    if (empty) throw new Error(`legal/terms.md: the section "${empty[0]}" has no text`);
    return { title, dateLine, sections, contact: last };
}

/** The TypeScript module src/ui/legal-terms.ts, generated from the markdown's exact bytes. */
export function generate(md) {
    const { title, dateLine, sections, contact } = parseTerms(md);
    const s = JSON.stringify;
    const sha256 = createHash("sha256").update(md).digest("hex");
    return [
        "// Generated by scripts/gen-legal.mjs from legal/terms.md. ⛔ Do not edit: change the markdown and run `node scripts/gen-legal.mjs`.",
        `// legal/terms.md sha256 ${sha256}`,
        `export const TERMS_TITLE = ${s(title)};`,
        `export const TERMS_DATE_LINE = ${s(dateLine)};`,
        "export const TERMS: [string, string[]][] = [",
        ...sections.map(([h, ps]) => `  [${s(h)}, [\n${ps.map((p) => `    ${s(p)},\n`).join("")}  ]],`),
        "];",
        `export const CONTACT = ${s(contact)};`,
        "",
    ].join("\n");
}
